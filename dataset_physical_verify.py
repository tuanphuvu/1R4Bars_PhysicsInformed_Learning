#dataset_physical_verify.py

#
# Validates data/saved/train.npz and data/saved/ood_test.npz
# with 4 tests before any model is trained.
#
# ┌──────────────────────────────────────────────────────────────────┐
# │                                │
# │                                                                  │
# │  "Garbage in, garbage out."  If the dataset has physics errors,  │
# │  degenerate coverage, or numerical issues, the PINN will learn   │
# │  wrong parameters θ with high confidence — undetectable later.   │
# │                                                                  │
# │  Test 1 — Physics Residual                                       │
# │    inverse_dynamics(q, dq, ddq, F_log[i]) ≈ τ_saved?            │
# │    Each sample uses its own logged force (time-varying).         │
# │    Checks: was the CTC pipeline internally consistent?           │
# │                                                                  │
# │  Test 2 — Coverage & Excitation                                  │
# │    Are joint ranges wide enough?                                 │
# │    Does the robot actually move (non-degenerate dq, τ)?          │
# │    Insufficient excitation → some θ components unidentifiable.   │
# │                                                                  │
# │  Test 3 — Numerical Quality                                      │
# │    NaN / Inf / spline oscillation / magnitude bounds.            │
# │    Bad numerics can cause gradient explosion in PINN training.   │
# │                                                                  │
# │  Test 4 — Force Log Sanity                                       │
# │    |F(t)| ∈ [5, 15] N  and  θ ∈ [−90°, +30°] ?                 │
# │    Checks the time-varying force profile is physically valid.    │
# └──────────────────────────────────────────────────────────────────┘

import sys, os
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from dynamics.matrices import inverse_dynamics
from dynamics.params   import Q1_MIN, Q1_MAX, Q2_MIN, Q2_MAX

# ══════════════════════════════════════════════════════════════════════════
# THRESHOLDS
# ══════════════════════════════════════════════════════════════════════════
PHYS_RMSE_MAX   = 5.0    # N·m   — physics residual  (generous: allows PD term)
MIN_Q_COVERAGE  = 0.20   # frac  — must cover ≥20% of each joint's full range
MIN_DQ_STD      = 0.01   # rad/s — robot must actually be moving
MIN_TAU_STD     = 0.10   # N·m   — must have torque variation (excitation)
MAX_DDQ         = 200.0  # rad/s²— spline oscillation guard
MAX_TAU         = 200.0  # N·m   — magnitude sanity
N_CHECK         = 500    # random samples used in physics residual check

# Force profile bounds (must match generate_dataset.py)
FORCE_MAG_MIN   = 5.0    # N
FORCE_MAG_MAX   = 15.0   # N
FORCE_ANG_MIN   = -90.0  # degrees
FORCE_ANG_MAX   =  30.0  # degrees
FORCE_MAG_TOL   =  0.5   # N   — allow small numerical overshoot from spline

os.makedirs("figures", exist_ok=True)

# ══════════════════════════════════════════════════════════════════════════
# LOAD
# ══════════════════════════════════════════════════════════════════════════
print("\nLoading datasets...")

for path in ["data/saved/train.npz", "data/saved/ood_test.npz"]:
    if not os.path.exists(path):
        raise FileNotFoundError(f"{path} not found — run data/generate_dataset.py first.")

train = np.load("data/saved/train.npz")
ood   = np.load("data/saved/ood_test.npz")

print(f"  TRAIN : {len(train['q']):,} samples   keys: {list(train.keys())}")
print(f"  OOD   : {len(ood['q']):,}   samples   keys: {list(ood.keys())}")

# Warn if F_log is missing (old dataset format)
for name, ds in [("TRAIN", train), ("OOD", ood)]:
    if 'F_log' not in ds:
        print(f"  [!!]  {name}: 'F_log' key missing — regenerate with updated generate_dataset.py")

# ── Helpers ───────────────────────────────────────────────────────────────
results = []   # accumulated PASS/FAIL booleans

def rmse(a, b):
    return float(np.sqrt(np.mean((a - b) ** 2)))

def check(condition, label, detail=""):
    tag  = "[ok] PASS" if condition else "[!!] FAIL"
    line = f"  {tag}  {label}"
    if detail:
        line += f"  |  {detail}"
    print(line)
    results.append(condition)
    return condition

# ══════════════════════════════════════════════════════════════════════════
# TEST 1 — PHYSICS RESIDUAL
# ══════════════════════════════════════════════════════════════════════════
# What it checks
# ──────────────
# The dataset was generated by: simulate CTC → record (q_sim, dq_sim, ddq_sim, τ_sim).
# If the pipeline is correct, the inverse dynamics equation must hold:
#
#   τ_check = M(q)·ddq + C(q,dq)·dq + g(q) − QF(q, F_log[i])  ≈  τ_saved
#
# Each sample uses its own logged force F_log[i] (time-varying, no delay).
# The small residual comes from the PD correction term M·(Kd·ė + Kp·e),
# which should be ≈ 0 when tracking error is tiny.
# A large RMSE signals a bug (wrong ddq computation, wrong model, etc.).

print("\n" + "═"*60)
print("  TEST 1 — PHYSICS RESIDUAL")
print("  inverse_dynamics(q, dq, ddq, F_log[i])  ≈  τ_saved ?")
print("═"*60)

phys_info = {}   # store for plotting

for name, ds in [("TRAIN", train), ("OOD", ood)]:
    N   = len(ds['q'])
    rng = np.random.default_rng(42)
    idx = rng.choice(N, min(N_CHECK, N), replace=False)

    has_f = 'F_log' in ds
    τ_check = np.array([
        inverse_dynamics(ds['q'][i], ds['dq'][i], ds['ddq'][i],
                         ds['F_log'][i] if has_f else np.zeros(2))
        for i in idx
    ])
    τ_saved  = ds['tau'][idx]
    residual = τ_check - τ_saved
    r        = rmse(τ_check, τ_saved)

    phys_info[name] = {'residual': residual, 'rmse': r, 'tau_saved': τ_saved}

    ok = r < PHYS_RMSE_MAX
    check(ok, f"{name}: physics RMSE = {r:.4f} N·m",
          f"threshold = {PHYS_RMSE_MAX} N·m")
    print(f"          τ₁ RMSE = {rmse(τ_check[:,0], τ_saved[:,0]):.5f} N·m"
          f"   τ₂ RMSE = {rmse(τ_check[:,1], τ_saved[:,1]):.5f} N·m")

# ══════════════════════════════════════════════════════════════════════════
# TEST 2 — COVERAGE & EXCITATION
# ══════════════════════════════════════════════════════════════════════════
# What it checks
# ──────────────
# For parameter identification (PINN goal), the training data must
# "persistently excite" the dynamics in all directions:
#   • Wide q range  → identifies position-dependent terms (M, g)
#   • Non-zero dq   → identifies velocity-dependent terms (C)
#   • Non-zero τ variation → confirms torques are not trivially zero
#
# Narrow coverage → PINN can fit τ correctly on training data but will
# learn degenerate θ that fail to extrapolate.

print("\n" + "═"*60)
print("  TEST 2 — COVERAGE & EXCITATION")
print("═"*60)

for name, ds in [("TRAIN", train), ("OOD", ood)]:
    print(f"\n  ── {name} ──")
    q   = ds['q'];   dq = ds['dq'];   tau = ds['tau']

    # Joint angle coverage (fraction of full range from params)
    q1_range  = q[:, 0].max() - q[:, 0].min()
    q2_range  = q[:, 1].max() - q[:, 1].min()
    q1_limit  = Q1_MAX - Q1_MIN
    q2_limit  = Q2_MAX - Q2_MIN
    cov1, cov2 = q1_range / q1_limit, q2_range / q2_limit

    check(cov1 >= MIN_Q_COVERAGE,
          f"{name} q₁ coverage = {cov1*100:.0f}%",
          f"{np.degrees(q1_range):.1f}° / {np.degrees(q1_limit):.1f}°  "
          f"(min {MIN_Q_COVERAGE*100:.0f}%)")
    check(cov2 >= MIN_Q_COVERAGE,
          f"{name} q₂ coverage = {cov2*100:.0f}%",
          f"{np.degrees(q2_range):.1f}° / {np.degrees(q2_limit):.1f}°  "
          f"(min {MIN_Q_COVERAGE*100:.0f}%)")

    # Velocity excitation (robot must be moving)
    dq_std = dq.std(axis=0)
    check(dq_std.min() >= MIN_DQ_STD,
          f"{name} velocity std  = [{dq_std[0]:.4f}, {dq_std[1]:.4f}] rad/s",
          f"min threshold = {MIN_DQ_STD}")

    # Torque excitation (sufficient variation to identify parameters)
    tau_std = tau.std(axis=0)
    check(tau_std.min() >= MIN_TAU_STD,
          f"{name} torque std   = [{tau_std[0]:.3f}, {tau_std[1]:.3f}] N·m",
          f"min threshold = {MIN_TAU_STD}")

    print(f"    q₁ ∈ [{np.degrees(q[:,0].min()):+.1f}°, {np.degrees(q[:,0].max()):+.1f}°]  "
          f"q₂ ∈ [{np.degrees(q[:,1].min()):+.1f}°, {np.degrees(q[:,1].max()):+.1f}°]")
    print(f"    |dq| max = {np.abs(dq).max():.3f} rad/s  "
          f"   |τ|  max = {np.abs(tau).max():.2f} N·m")

# ══════════════════════════════════════════════════════════════════════════
# TEST 3 — NUMERICAL QUALITY
# ══════════════════════════════════════════════════════════════════════════
# What it checks
# ──────────────
# NaN / Inf → crash during PINN training.
# Large |ddq| → CubicSpline oscillation between IK-solved waypoints;
#               causes PINN loss to be dominated by high-frequency artifacts.
# Large |τ|  → check if torques are physically plausible for the robot.
# TRAIN/OOD q-mean diff → sanity that both datasets live in same workspace.

print("\n" + "═"*60)
print("  TEST 3 — NUMERICAL QUALITY")
print("═"*60)

for name, ds in [("TRAIN", train), ("OOD", ood)]:
    print(f"\n  ── {name} ──")
    arrays_to_check = [ds['q'], ds['dq'], ds['ddq'], ds['tau']]
    if 'F_log' in ds:
        arrays_to_check.append(ds['F_log'])
    all_vals = np.concatenate(arrays_to_check, axis=1)

    has_nan = bool(np.isnan(all_vals).any())
    has_inf = bool(np.isinf(all_vals).any())
    check(not has_nan and not has_inf,
          f"{name} NaN/Inf free",
          f"NaN={has_nan}  Inf={has_inf}")

    ddq_max = float(np.abs(ds['ddq']).max())
    check(ddq_max < MAX_DDQ,
          f"{name} |ddq| max = {ddq_max:.2f} rad/s²",
          f"threshold = {MAX_DDQ}")

    tau_max = float(np.abs(ds['tau']).max())
    check(tau_max < MAX_TAU,
          f"{name} |τ| max = {tau_max:.2f} N·m",
          f"threshold = {MAX_TAU}")

# Cross-dataset: q means should be close (same workspace, different amplitude)
q_mean_diff = np.abs(train['q'].mean(0) - ood['q'].mean(0))
check(np.degrees(q_mean_diff).max() < 20.0,
      f"TRAIN / OOD q-mean diff = [{np.degrees(q_mean_diff[0]):.1f}°, "
      f"{np.degrees(q_mean_diff[1]):.1f}°]",
      "expect < 20° (same workspace)")

# ══════════════════════════════════════════════════════════════════════════
# TEST 4 — FORCE LOG SANITY
# ══════════════════════════════════════════════════════════════════════════
# What it checks
# ──────────────
# The time-varying force F(t) must stay within the generation bounds:
#   |F(t)| ∈ [FORCE_MAG_MIN − tol, FORCE_MAG_MAX + tol]
#   angle(F(t)) ∈ [FORCE_ANG_MIN − tol, FORCE_ANG_MAX + tol]
# A small tolerance accounts for CubicSpline overshoot between segments.
# TRAIN and OOD should have different force profiles (independent random seeds),
# verified by checking that their mean force directions differ.

print("\n" + "═"*60)
print("  TEST 4 — FORCE LOG SANITY")
print(f"  Expected: |F| ∈ [{FORCE_MAG_MIN}, {FORCE_MAG_MAX}] N   "
      f"θ ∈ [{FORCE_ANG_MIN}°, {FORCE_ANG_MAX}°]")
print("═"*60)

for name, ds in [("TRAIN", train), ("OOD", ood)]:
    print(f"\n  ── {name} ──")
    if 'F_log' not in ds:
        print(f"     [ok]  F_log missing — skipping Test 4 for {name}")
        results.append(False)
        continue

    F = ds['F_log']                               # (N, 2)
    mag   = np.linalg.norm(F, axis=1)            # (N,)
    angle = np.degrees(np.arctan2(F[:, 1], F[:, 0]))  # (N,)  in [−180, +180]

    mag_ok = (mag.min() >= FORCE_MAG_MIN - FORCE_MAG_TOL and
              mag.max() <= FORCE_MAG_MAX + FORCE_MAG_TOL)
    check(mag_ok,
          f"{name} |F| ∈ [{mag.min():.2f}, {mag.max():.2f}] N",
          f"expect [{FORCE_MAG_MIN - FORCE_MAG_TOL:.1f}, "
          f"{FORCE_MAG_MAX + FORCE_MAG_TOL:.1f}] N (±{FORCE_MAG_TOL} N tol)")

    ang_ok = (angle.min() >= FORCE_ANG_MIN - 5.0 and
              angle.max() <= FORCE_ANG_MAX + 5.0)
    check(ang_ok,
          f"{name} θ ∈ [{angle.min():.1f}°, {angle.max():.1f}°]",
          f"expect [{FORCE_ANG_MIN}°, {FORCE_ANG_MAX}°] (±5° tol)")

    print(f"    mean |F| = {mag.mean():.2f} N   std = {mag.std():.2f} N")
    print(f"    mean  θ  = {angle.mean():.1f}°  std = {angle.std():.1f}°")

# TRAIN vs OOD force profiles should be independent (different random seeds)
if 'F_log' in train and 'F_log' in ood:
    N_min = min(len(train['F_log']), len(ood['F_log']))
    F_diff = np.abs(train['F_log'][:N_min] - ood['F_log'][:N_min]).mean()
    check(F_diff > 0.5,
          f"TRAIN / OOD force profiles differ   mean |ΔF| = {F_diff:.3f} N",
          "expect > 0.5 N (independent random seeds per trajectory)")

# ══════════════════════════════════════════════════════════════════════════
# FINAL SUMMARY
# ══════════════════════════════════════════════════════════════════════════
n_pass  = sum(results)
n_total = len(results)

print("\n" + "═"*60)
if n_pass == n_total:
    print(f"  [ok]  ALL {n_total} TESTS PASS  →  Dataset ready to train")
else:
    fails = [i+1 for i, r in enumerate(results) if not r]
    print(f"  [!!]   {n_pass}/{n_total} passed  →  Fix tests {fails} before training")
print("═"*60)

