ax = fig.add_subplot(gs[2, 0])
if 'F_log' in train and 'F_log' in ood:
    mag_tr  = np.linalg.norm(train['F_log'], axis=1)
    mag_ood = np.linalg.norm(ood['F_log'],   axis=1)
    ax.hist(mag_tr,  bins=60, color=c_tr,  alpha=0.6, density=True, label='TRAIN')
